"""Writes F7_HPAIR_PIXDIFF.md from f7_hpair_pixdiff.json + f7b_noisefloor.json."""
import json
import os
import numpy as np

OUT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
R = json.load(open(os.path.join(OUT, "f7_hpair_pixdiff.json")))
N = json.load(open(os.path.join(OUT, "f7b_noisefloor.json")))
TOT = 1920 * 1080


def f(x, nd=3):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{nd}f}"


L = []
L.append("# F7 — strict-H twin pixel-difference audit (RED-TEAM RESPONSE, D35 / R1-F7)\n")
L.append("Generated by `rt_response/code/f7_hpair_pixdiff.py` (+ `f7b_noisefloor.py`, "
         "`fig_f7_panels.py`) · CPU · read-only over the frozen renders.\n")
L.append("**The question.** strict-H is a *geometric* predicate — `int_px == 0 ∧ edge_vis == 0`, "
         "i.e. the hazard prism re-projects to zero pixels.  It does not forbid the hazard from "
         "changing the image through shadow, ambient occlusion, GI bounce, mesh seams or "
         "sub-threshold silhouettes.  R1-F7 asked what is actually left.  All 96 test H twin pairs "
         "were re-read at native 1920×1080 and differenced: `d = max_c |on_c − off_c|`.\n")
L.append("**Pairing gate.** All 96 pairs verified pose-exact to 1e-6 on "
         "(d, h_rel, yaw, pitch, roll, hfov, ground_z) — consistent with `METRICS.md` N.1 "
         "(H: 96 EXACT / 0 TOL / 0 EXCL).\n")

L.append("\n## 0. The threshold has to be calibrated first — the brief's 2/255 is renderer noise\n")
L.append("`sceneN3`'s `keep_dressing` off arm is **geometrically identical** to its on arm "
         "(`ctrl_dressing/CTRL_TABLE.md`: heightmap `max |Δ| = 0.000000 m`, NaN pattern equal), so "
         "every pixel that differs between those two renders is path-tracer / OptiX-denoiser "
         "nondeterminism.  Measured over its 24 cuts:\n")
nf = N["groups"]["noise_floor__N3_on_vs_keepdressing_off"]
ho = N["groups"]["hazard_only__C2_on_vs_keepdressing_off"]
L.append("| reference pair | n | median px ≥ 2/255 | median px ≥ 8/255 | **median px ≥ 32/255** | "
         "median mean-magnitude over changed px |")
L.append("|---|---|---|---|---|---|")
L.append("| **renderer noise floor** — N3 on vs N3 keep-dressing off (identical geometry) | %d | "
         "%.0f (%.1f %% of frame) | %.0f | **%.0f** | %.2f |" % (
             nf["n_pairs"], nf["n_diff_px_median"], 100 * nf["frac_diff_median"],
             nf["n_diff_px_ge8_median"], nf["n_diff_px_ge32_median"],
             nf["mean_diff_over_changed_median"]))
L.append("| hazard-only — C2 on vs C2 keep-dressing off (drop deleted, dressing kept) | %d | "
         "%.0f | %.0f | %.0f | %.2f |" % (
             ho["n_pairs"], ho["n_diff_px_median"], ho["n_diff_px_ge8_median"],
             ho["n_diff_px_ge32_median"], ho["mean_diff_over_changed_median"]))
L.append("\n**A 2/255 threshold flips 44 % of the frame on two renders of the same geometry.** "
         "Every statistic below is therefore reported at three levels, and **≥ 32/255 is the level "
         "that carries scene content** — its noise floor is 50 pixels out of 2 073 600.\n")

L.append("\n## 1. Headline — how much optical signal survives strict-H\n")
L.append("| set | n pairs | pairs with **zero** diff | median px ≥ 2 | median px ≥ 8 | "
         "**median px ≥ 32** | min px ≥ 32 | **median frac of frame ≥ 32** | × noise floor |")
L.append("|---|---|---|---|---|---|---|---|---|")
for key, name in (("all", "all test strict-H"), ("scene14", "scene14 (n=60)"),
                  ("scene15", "scene15 (n=36)")):
    d = R["all"] if key == "all" else R["by_scene"][key]
    lv = d["levels"]
    L.append("| %s | %d | **%d** | %.0f | %.0f | **%.0f** | %.0f | **%.4f** | ×%.0f |" % (
        name, d["n_pairs"], d["n_pairs_zero_diff"], lv["2"]["n_diff_px_median"],
        lv["8"]["n_diff_px_median"], lv["32"]["n_diff_px_median"],
        lv["32"]["n_diff_px_min"], lv["32"]["frac_diff_median"],
        lv["32"]["n_diff_px_median"] / nf["n_diff_px_ge32_median"]))

L.append("\n**Verdict: strict-H is never optically empty in this corpus.** "
         "0 of 96 pairs are byte-identical; the *quietest* pair still carries "
         f"{R['all']['levels']['32']['n_diff_px_min']:.0f} pixels at ≥ 32/255 — "
         f"{R['all']['levels']['32']['n_diff_px_min'] / nf['n_diff_px_ge32_median']:.0f}× the "
         "renderer noise floor.  The zero-difference consistency gate R1-F7 asked for is "
         "therefore vacuous here (no pair to test it on), and the honest reading is the "
         "opposite of the one it was set up to check: an H-tier twin Δ > 0 does **not** require "
         "an explanation beyond ordinary visual evidence.\n")

L.append("\n## 2. Where the residual sits\n")
L.append("Two reference regions, both projected with the canonical labeler camera model: the "
         "**GT-positive polar wedges** (the ground cells the metric scores) and the **amodal "
         "hazard silhouette** (the prism projected *ignoring* occlusion — where the hazard would "
         "be if nothing stood in front).  Shares are of the residual pixels at that level.\n")
L.append("| set | level | in GT wedges | in the 20-cell grid footprint | **in the amodal silhouette** | "
         "share of the amodal silhouette that is changed |")
L.append("|---|---|---|---|---|---|")
for key, name in (("all", "all"), ("scene14", "scene14"), ("scene15", "scene15")):
    d = R["all"] if key == "all" else R["by_scene"][key]
    for lv in ("2", "8", "32"):
        c = d["levels"][lv]
        L.append("| %s | ≥%s/255 | %s | %s | **%s** | %s |" % (
            name, lv, f(c["frac_in_gt_wedge_mean"]), f(c["frac_in_grid_mean"]),
            f(c["frac_in_amodal_mean"]), f(c["amodal_coverage_mean"])))
L.append("\n**Caveat that must travel with the amodal column.** For a fully occluded hazard the "
         "amodal silhouette necessarily covers the occluder as well — in scene14 it spans the "
         "plaza and the building base the drop hides behind (`METRICS_NOTES_yolo.md` §4 says so "
         "explicitly).  A high containment share therefore means *the residual is co-located with "
         "the hazard's line of sight*, not *the residual is the hazard's own pixels*.\n")

L.append("\n## 3. scene14 vs scene15 — the split that matters\n")
s14, s15 = R["by_scene"]["scene14"], R["by_scene"]["scene15"]
L.append("| quantity | scene14 (n=60) | scene15 (n=36) | ratio |")
L.append("|---|---|---|---|")
rows = [("median px ≥ 32/255", s14["levels"]["32"]["n_diff_px_median"],
         s15["levels"]["32"]["n_diff_px_median"]),
        ("p90 px ≥ 32/255", s14["levels"]["32"]["n_diff_px_p90"],
         s15["levels"]["32"]["n_diff_px_p90"]),
        ("median mean-magnitude over changed px",
         s14["mean_diff_over_changed_median"], s15["mean_diff_over_changed_median"]),
        ("median max abs Δ (per pair)", s14["max_diff_median"], s15["max_diff_median"])]
for nm, a, b in rows:
    L.append(f"| {nm} | {a:,.2f} | {b:,.2f} | ×{a/b:.1f} |")
L.append("| share of residual inside the GT wedges (≥2/255) | %s | %s | — |" % (
    f(s14["levels"]["2"]["frac_in_gt_wedge_mean"]), f(s15["levels"]["2"]["frac_in_gt_wedge_mean"])))
L.append("\nAt the noise-dominated 2/255 level the two scenes look identical (median frac 0.197 "
         "both) — that is the noise, not the scene.  At 32/255 scene14's residual is **22× larger "
         "in count** and its per-pixel magnitude is **7.6× larger**, and scene15's mean magnitude "
         "over changed pixels (%.2f) is only %.1f× the renderer noise floor (%.2f).\n" % (
             s15["mean_diff_over_changed_median"],
             s15["mean_diff_over_changed_median"] / nf["mean_diff_over_changed_median"],
             nf["mean_diff_over_changed_median"]))
L.append("**This is the same 60/36 split that carries the twin Δ.** R2 §4.3 measured H twin Δ "
         "scene14 rgb .278/.448/.558 · depth .577–.645 versus scene15 rgb −.010/.209/−.058 · "
         "depth .016–.150.  The scene whose model response is real is the scene with a large "
         "supra-noise residual; the scene where Δ ≈ 0 is the scene whose residual is a small "
         "patch near the noise floor.  The two independent measurements agree.\n")

L.append("\n## 4. Does the residual predict the model's twin Δ?\n")
L.append("Spearman ρ between log10(residual pixels ≥ 32/255) and that pair's `delta_score`, over "
         "the 96 kept H pairs.  A positive ρ says the model responds more where more is visible.\n")
L.append("| run | ρ (96 pairs, pooled) | ρ within scene14 | ρ within scene15 | "
         "mean Δ, quietest scene14 third | mean Δ, loudest scene14 third |")
L.append("|---|---|---|---|---|---|")
for run, c in R["coupling"].items():
    L.append("| %s | **%s** | %s | %s | %s | %s |" % (
        run, f(c["spearman_logL32px_vs_delta"]), f(c.get("spearman_scene14")),
        f(c.get("spearman_scene15")), f(c.get("s14_delta_mean_quiet_tercile")),
        f(c.get("s14_delta_mean_loud_tercile"))))
L.append("\nAll nine pooled ρ are positive (0.27–0.83).  The pooled value is partly the "
         "two-scene contrast of §3, so the within-scene columns are the load-bearing ones: "
         "**Depth is positive in all six within-scene cells (0.08–0.69) and its scene14 "
         "quiet→loud tercile Δ rises 0.34–0.40 → 0.83–0.93; RGB is inconsistent** "
         "(−0.13 to +0.39 within scene, tercile Δ 0.44→0.43 on seed 43).  Read: the residual "
         "optical evidence is what the *Depth* arm tracks; the RGB arm's H response is not "
         "graded by how much is visible, which is consistent with its twin-conditional deficit "
         "(F2: 45 % of RGB's H fires also fire on the hazard-deleted twin).\n")

L.append("\n## 5. What the toggle actually removes — the scope limit on every Δ in this paper\n")
L.append("The corpus twin flips `SCENE_CONFIG['hazard_stairs']`.  In `scene14` that branch builds "
         "the shoulder massif, the side slopes, the stair, the step coursing, the parapets, the "
         "cues **and** the autumn litter; `False` replaces all of it with a flat fill "
         "(`scenes/main/scene14_grandstair_illusion.py:1885-1898`).  In `scene15` it removes the "
         "stair and the bend and extends the upper alley flat "
         "(`scenes/main/scene15_alley_labyrinth.py:2301-2304`).  The residual measured above is "
         "therefore the union of {the drop's indirect optics} ∪ {every object inside that branch}, "
         "which is exactly the qualifier R1-F12 asked for.  For contrast, the one place where the "
         "hazard alone is removed — sceneC2's `keep_dressing` arm — still moves %.0f px at "
         "≥ 32/255.\n" % ho["n_diff_px_ge32_median"])
L.append("Tier cross-check inside the same two scenes (main round, ≥ 32/255 medians): "
         + " · ".join(f"{k.split('__',1)[1].replace('__',' / ')} = {v['n_diff_px_ge32_median']:,.0f} px"
                      for k, v in N["groups"].items() if k.startswith("tiercheck__")) + ".\n")

L.append("\n## 6. Figures\n")
L.append("`panels/h_diff_contact_sheet.png` — all six pairs.  Individual panels: "
         "`panels/h_diff_scene14_{min,median,max}.png`, `panels/h_diff_scene15_{min,median,max}.png`.  "
         "Selection rule (fixed before looking at any image): within each scene, the pair at the "
         "minimum, the median and the maximum residual at ≥ 32/255.\n")
L.append("| panel | frame | standoff | px ≥ 32/255 | % of frame | in amodal | in GT wedges |")
L.append("|---|---|---|---|---|---|---|")
for sc in ("scene14", "scene15"):
    rows_ = sorted([r for r in R["per_pair"] if r["scene_id"] == sc],
                   key=lambda r: r["L32"]["n_diff_px"])
    for tag, r in (("min", rows_[0]), ("median", rows_[len(rows_) // 2]), ("max", rows_[-1])):
        c = r["L32"]
        L.append("| %s / %s | `%s` | %.2f m | %s | %.2f %% | %s | %s |" % (
            sc, tag, os.path.basename(r["frame_id"]), r["cam_d"], f"{c['n_diff_px']:,}",
            100 * c["frac_diff"], f(c["frac_in_amodal"]), f(c["frac_in_gt_wedge"])))

open(os.path.join(OUT, "F7_HPAIR_PIXDIFF.md"), "w").write("\n".join(L) + "\n")
print("wrote F7_HPAIR_PIXDIFF.md")
