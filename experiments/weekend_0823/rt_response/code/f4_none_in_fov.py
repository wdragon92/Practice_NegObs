"""F4 — none_in_fov FIRING RATE (D35 / R1-F4) and the N.3 null-control reinterpretation.

`none_in_fov` = a hazard-ON frame whose hazard projects to no positive cell inside the
20-cell grid (outside 12 m, or outside +-31.1 deg).  Its GT row is all-zero, so every
firing is a false positive — but the tier sits in NEITHER denominator: not in recall
(no positive cell) and not in the off-arm FA rate (it is an on-arm frame).  81 of the
816 test rows are in this hole.

Also recomputes the sceneN3 numbers behind `METRICS.md` R.3 / `RESULTS_DRAFT` R.3, which
called the null control "behaved as designed".

Outputs: f4_none_in_fov.json, F4_NONE_IN_FOV.md
"""
import json
import os
import numpy as np
from common_rt import MODELS, SEEDS, RUNS, load_per_frame, mean_hr, halfrange

OUT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
TAU = 0.5

D = {r: load_per_frame(r) for r in RUNS}
res = {"tau": TAU, "runs": {}, "model_mean": {}, "per_scene": {}, "provenance": {
    "input": "experiments/dayrun_0820/runs/v2/*/eval_test/per_frame.csv",
    "definition": "none_in_fov = toggle_state 'on', tier 'none_in_fov'; GT is all-zero, "
                  "so frame firing rate = false-alarm rate on a tier that is in no denominator",
}}

scenes_nif = sorted({r["scene_id"] for r in D["rgb_s42"] if r["tier"] == "none_in_fov"})
for run in RUNS:
    rows = D[run]
    nif = [r for r in rows if r["tier"] == "none_in_fov"]
    off = [r for r in rows if r["toggle"] == "off"]
    e = {"n_none_in_fov": len(nif),
         "fire_rate_none_in_fov": float(np.mean([(r["p"] >= TAU).any() for r in nif])),
         "frame_fa_off": float(np.mean([(r["p"] >= TAU).any() for r in off])),
         "cells_per_frame_none_in_fov": float(np.mean([(r["p"] >= TAU).sum() for r in nif])),
         "mean_max_p_none_in_fov": float(np.mean([r["p"].max() for r in nif])),
         "per_scene": {}}
    e["ratio_to_reported_fa"] = (e["fire_rate_none_in_fov"] / e["frame_fa_off"]
                                 if e["frame_fa_off"] > 0 else float("inf"))
    for sc in scenes_nif:
        sel = [r for r in nif if r["scene_id"] == sc]
        e["per_scene"][sc] = {"n": len(sel),
                              "fire_rate": float(np.mean([(r["p"] >= TAU).any() for r in sel]))}
    # sceneN3, both arms — the null control
    n3_on = [r for r in rows if r["scene_id"] == "sceneN3" and r["toggle"] == "on"]
    n3_off = [r for r in rows if r["scene_id"] == "sceneN3" and r["toggle"] == "off"]
    e["sceneN3"] = {
        "n_on": len(n3_on), "n_off": len(n3_off),
        "on_fire_rate": float(np.mean([(r["p"] >= TAU).any() for r in n3_on])),
        "off_fire_rate": float(np.mean([(r["p"] >= TAU).any() for r in n3_off])),
        "on_mean_max_p": float(np.mean([r["p"].max() for r in n3_on])),
        "off_mean_max_p": float(np.mean([r["p"].max() for r in n3_off])),
        "on_cells_per_frame": float(np.mean([(r["p"] >= TAU).sum() for r in n3_on])),
        "off_cells_per_frame": float(np.mean([(r["p"] >= TAU).sum() for r in n3_off])),
        "on_tiers": sorted({r["tier"] for r in n3_on}),
    }
    res["runs"][run] = e

for m in MODELS:
    keys = ["fire_rate_none_in_fov", "frame_fa_off", "cells_per_frame_none_in_fov",
            "mean_max_p_none_in_fov", "ratio_to_reported_fa"]
    res["model_mean"][m] = {
        k: {"mean": mean_hr([res["runs"][f"{m}_s{s}"][k] for s in SEEDS]),
            "half_range": halfrange([res["runs"][f"{m}_s{s}"][k] for s in SEEDS]),
            "per_seed": [res["runs"][f"{m}_s{s}"][k] for s in SEEDS]} for k in keys}
    res["model_mean"][m]["sceneN3"] = {
        k: {"mean": mean_hr([res["runs"][f"{m}_s{s}"]["sceneN3"][k] for s in SEEDS]),
            "per_seed": [res["runs"][f"{m}_s{s}"]["sceneN3"][k] for s in SEEDS]}
        for k in ("on_fire_rate", "off_fire_rate", "on_mean_max_p", "off_mean_max_p")}

json.dump(res, open(os.path.join(OUT, "f4_none_in_fov.json"), "w"), indent=1)


def f(x, nd=3):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{nd}f}"


L = []
L.append("# F4 — the `none_in_fov` accounting hole (RED-TEAM RESPONSE, D35 / R1-F4)\n")
L.append("Generated by `rt_response/code/f4_none_in_fov.py` · CPU · read-only.\n")
L.append("`none_in_fov` is a hazard-ON frame whose hazard falls outside the grid (past 12 m or "
         "outside ±31.1°).  Its GT row is all-zero, so **every firing is a false positive** — yet "
         "the tier is in neither published denominator: not in recall (no GT-positive cell) and "
         "not in `frame_fa_off` (it is an on-arm frame).  **81 of the 816 test rows** "
         "(19.9 % of the 408 hazard-ON rows) sit in that hole.\n")

L.append("\n## 1. Firing rate on the uncounted tier, τ = 0.5\n")
L.append("| run | n | **`FA_in-scene`** (none_in_fov fire rate) | reported `frame_fa_off` | ratio | "
         "cells/frame | mean max p |")
L.append("|---|---|---|---|---|---|---|")
R1_PUB = {"rgb_s42": 0.790, "rgb_s43": 0.963, "rgb_s44": 0.642,
          "depth_s42": 0.593, "depth_s43": 0.444, "depth_s44": 0.444}
for run in RUNS:
    e = res["runs"][run]
    L.append("| %s | %d | **%s** | %s | ×%.1f | %s | %s |" % (
        run, e["n_none_in_fov"], f(e["fire_rate_none_in_fov"]), f(e["frame_fa_off"]),
        e["ratio_to_reported_fa"], f(e["cells_per_frame_none_in_fov"], 2),
        f(e["mean_max_p_none_in_fov"])))
L.append("\n**Verification against R1-F4** (`r2.py` §C):\n")
L.append("| run | R1 published | recomputed | match |")
L.append("|---|---|---|---|")
for run, v in R1_PUB.items():
    got = res["runs"][run]["fire_rate_none_in_fov"]
    L.append(f"| {run} | {v:.3f} | {got:.3f} | {'✓' if abs(got - v) < 1e-3 else '✗'} |")

L.append("\n**3-seed mean:**\n")
L.append("| model | `FA_in-scene` | reported `frame_fa_off` | ratio |")
L.append("|---|---|---|---|")
for m in MODELS:
    mm = res["model_mean"][m]
    L.append("| %s | **%s ±%s** | %s ±%s | ×%.1f |" % (
        m, f(mm["fire_rate_none_in_fov"]["mean"]), f(mm["fire_rate_none_in_fov"]["half_range"]),
        f(mm["frame_fa_off"]["mean"]), f(mm["frame_fa_off"]["half_range"]),
        mm["fire_rate_none_in_fov"]["mean"] / mm["frame_fa_off"]["mean"]))

L.append("\n## 2. By scene\n")
L.append("| run | " + " | ".join(f"{sc} (n={res['runs']['rgb_s42']['per_scene'][sc]['n']})"
                                 for sc in scenes_nif) + " |")
L.append("|---" * (len(scenes_nif) + 1) + "|")
for run in RUNS:
    L.append("| %s | %s |" % (run, " | ".join(
        f(res["runs"][run]["per_scene"][sc]["fire_rate"]) for sc in scenes_nif)))

L.append("\n## 3. sceneN3 — the null control, both arms\n")
L.append("sceneN3 is the hard negative: **no drop-off exists in either arm** (its 'hazard' is a "
         "trompe-l'œil wall mural, 1–2 mm of paint on flat floor).  `METRICS.md` R.3 and "
         "`RESULTS_DRAFT` R.3 record it as *behaved as designed* because its twin Δ measures "
         "−0.001.  Δ ≈ 0 is correct — but it is 0 because **both arms are saturated, not because "
         "both arms are quiet**:\n")
L.append("| run | on-arm fire rate | off-arm fire rate | on mean max p | off mean max p | "
         "on cells/frame | off cells/frame |")
L.append("|---|---|---|---|---|---|---|")
for run in RUNS:
    n3 = res["runs"][run]["sceneN3"]
    L.append("| %s | **%s** | **%s** | %s | %s | %s | %s |" % (
        run, f(n3["on_fire_rate"]), f(n3["off_fire_rate"]), f(n3["on_mean_max_p"]),
        f(n3["off_mean_max_p"]), f(n3["on_cells_per_frame"], 2), f(n3["off_cells_per_frame"], 2)))
L.append("\nAll 24 sceneN3 on-arm test frames carry tier %s — the scene has no hazard, so its "
         "on-arm rows are exactly the `none_in_fov` rows of §1." % res["runs"]["rgb_s42"]["sceneN3"]["on_tiers"])

open(os.path.join(OUT, "F4_NONE_IN_FOV.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L))
