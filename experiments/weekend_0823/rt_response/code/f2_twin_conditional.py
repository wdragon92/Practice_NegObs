"""F2 — TWIN-CONDITIONAL RECALL (D35 / R2 §4.3-F2).

A frame counts as a twin-conditional hit iff the model fires on a GT-positive cell
in the hazard-ON frame AND does NOT fire on the byte-paired hazard-OFF twin:

    hit(frame) = [ max_on_gt >= tau ]  AND  [ max_off_gt < tau ]      (tau = 0.5)

max_off_gt is the off-arm twin's maximum probability over the SAME cells that are
GT-positive on the on arm, so the two terms are read on identical cells of an
identical camera cut.  Pairs are the KEPT pairs of twin_pairs.csv.

Outputs: f2_twin_conditional.json, F2_TWIN_CONDITIONAL.md
"""
import json
import os
import numpy as np
from common_rt import MODELS, SEEDS, RUNS, load_twin, mean_hr, halfrange

OUT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
TAU = 0.5
TIERS = ("H", "E", "V")

res = {"tau": TAU, "runs": {}, "model_mean": {}, "per_scene": {}, "provenance": {
    "input": "experiments/dayrun_0820/runs/v2/{model}_s{seed}/twin/twin_pairs.csv",
    "definition": "hit = (max_on_gt >= tau) and (max_off_gt < tau), KEPT pairs only",
}}

T = {r: load_twin(r) for r in RUNS}

for run in RUNS:
    rows = [r for r in T[run] if r["kept"]]
    e = {}
    for tier in TIERS:
        sel = [r for r in rows if r["tier"] == tier]
        n = len(sel)
        if n == 0:
            e[tier] = None
            continue
        on_fire = sum(1 for r in sel if r["max_on_gt"] >= TAU)
        off_fire = sum(1 for r in sel if r["max_off_gt"] >= TAU)
        cond = sum(1 for r in sel if r["max_on_gt"] >= TAU and r["max_off_gt"] < TAU)
        both = sum(1 for r in sel if r["max_on_gt"] >= TAU and r["max_off_gt"] >= TAU)
        e[tier] = {
            "n_pairs": n,
            "recall_plain": on_fire / n,
            "recall_twin_conditional": cond / n,
            "off_arm_fire_rate": off_fire / n,
            "n_on_fire": on_fire, "n_cond_hit": cond, "n_unconditional_fire": both,
            "share_unconditional": (both / on_fire) if on_fire else float("nan"),
            "mean_max_on_gt": float(np.mean([r["max_on_gt"] for r in sel])),
            "mean_max_off_gt": float(np.mean([r["max_off_gt"] for r in sel])),
        }
    res["runs"][run] = e

for m in MODELS:
    mm = {}
    for tier in TIERS:
        cells = [res["runs"][f"{m}_s{s}"][tier] for s in SEEDS]
        if any(c is None for c in cells):
            mm[tier] = None
            continue
        mm[tier] = {k: {"mean": mean_hr([c[k] for c in cells]),
                        "half_range": halfrange([c[k] for c in cells]),
                        "per_seed": [c[k] for c in cells]}
                    for k in ("recall_plain", "recall_twin_conditional",
                              "off_arm_fire_rate", "share_unconditional")}
        mm[tier]["n_pairs"] = cells[0]["n_pairs"]
    res["model_mean"][m] = mm

# per-scene H breakdown (the F2/R2 scene-cluster story)
for run in RUNS:
    rows = [r for r in T[run] if r["kept"] and r["tier"] == "H"]
    scenes = sorted({r["scene_id"] for r in rows})
    res["per_scene"][run] = {}
    for sc in scenes:
        sel = [r for r in rows if r["scene_id"] == sc]
        n = len(sel)
        res["per_scene"][run][sc] = {
            "n": n,
            "recall_plain": sum(1 for r in sel if r["max_on_gt"] >= TAU) / n,
            "recall_twin_conditional": sum(1 for r in sel if r["max_on_gt"] >= TAU
                                           and r["max_off_gt"] < TAU) / n,
            "off_arm_fire_rate": sum(1 for r in sel if r["max_off_gt"] >= TAU) / n,
            "mean_max_on_gt": float(np.mean([r["max_on_gt"] for r in sel])),
            "mean_max_off_gt": float(np.mean([r["max_off_gt"] for r in sel])),
        }

json.dump(res, open(os.path.join(OUT, "f2_twin_conditional.json"), "w"), indent=1)


def f(x, nd=3):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{nd}f}"


L = []
L.append("# F2 — Twin-conditional recall (RED-TEAM RESPONSE, D35 / R2 §4.3-F2)\n")
L.append("Generated by `rt_response/code/f2_twin_conditional.py` · CPU · read-only over the frozen "
         "v2 twin dumps.\n")
L.append("**Definition.** A hazard-ON frame counts as a *twin-conditional* hit iff the model fires "
         "on a GT-positive cell **and** the byte-paired hazard-OFF twin of the same camera cut does "
         "**not** fire on those same cells:\n")
L.append("```\nhit(frame) = [ max_on_gt ≥ τ ]  ∧  [ max_off_gt < τ ]      τ = 0.5\n```\n")
L.append("The off arm costs no extra render and no extra inference — it is already in "
         "`twin/twin_pairs.csv`.  Pairs are the KEPT (pose-matched) pairs.\n")

L.append("\n## 1. Headline table — H / E / V, 3-seed mean ± half-range\n")
for tier in TIERS:
    n = res["model_mean"]["rgb"][tier]["n_pairs"] if res["model_mean"]["rgb"][tier] else 0
    L.append(f"\n**{tier} tier** (n = {n} kept pairs per run)\n")
    L.append("| model | recall (published rule) | **twin-conditional recall** | off-arm twin fire rate | "
             "share of fires that are unconditional |")
    L.append("|---|---|---|---|---|")
    for m in MODELS:
        c = res["model_mean"][m][tier]
        if c is None:
            L.append(f"| {m} | n/a | n/a | n/a | n/a |")
            continue
        ps = "/".join(f(x) for x in c["recall_twin_conditional"]["per_seed"])
        ofs = "/".join(f(x) for x in c["off_arm_fire_rate"]["per_seed"])
        L.append("| %s | %s ±%s | **%s ±%s** (%s) | %s (%s) | %s |" % (
            m, f(c["recall_plain"]["mean"]), f(c["recall_plain"]["half_range"]),
            f(c["recall_twin_conditional"]["mean"]), f(c["recall_twin_conditional"]["half_range"]), ps,
            f(c["off_arm_fire_rate"]["mean"]), ofs,
            f(c["share_unconditional"]["mean"])))

L.append("\n## 2. Verification against R2's published numbers\n")
L.append("| model | R2 published twin-conditional H | recomputed | match |")
L.append("|---|---|---|---|")
R2_PUB = {"rgb": 0.375, "depth": 0.438, "b2": 0.121}
for m in MODELS:
    got = res["model_mean"][m]["H"]["recall_twin_conditional"]["mean"]
    L.append(f"| {m} | {R2_PUB[m]:.3f} | {got:.3f} | "
             f"{'✓' if abs(got - R2_PUB[m]) < 1e-3 else '✗ DIFFERS'} |")

L.append("\n## 3. Per-run detail\n")
L.append("| run | tier | n | plain recall | twin-cond. recall | off-arm fire | mean max_on_gt | mean max_off_gt |")
L.append("|---|---|---|---|---|---|---|---|")
for run in RUNS:
    for tier in TIERS:
        c = res["runs"][run][tier]
        if c is None:
            continue
        L.append("| %s | %s | %d | %s | %s | %s | %s | %s |" % (
            run, tier, c["n_pairs"], f(c["recall_plain"]), f(c["recall_twin_conditional"]),
            f(c["off_arm_fire_rate"]), f(c["mean_max_on_gt"]), f(c["mean_max_off_gt"])))

L.append("\n## 4. H tier by scene — where the unconditional firing lives\n")
L.append("| run | scene | n | plain recall | twin-cond. recall | off-arm fire | mean max_on_gt | mean max_off_gt |")
L.append("|---|---|---|---|---|---|---|---|")
for run in RUNS:
    for sc, c in sorted(res["per_scene"][run].items()):
        L.append("| %s | %s | %d | %s | %s | %s | %s | %s |" % (
            run, sc, c["n"], f(c["recall_plain"]), f(c["recall_twin_conditional"]),
            f(c["off_arm_fire_rate"]), f(c["mean_max_on_gt"]), f(c["mean_max_off_gt"])))

open(os.path.join(OUT, "F2_TWIN_CONDITIONAL.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L))
