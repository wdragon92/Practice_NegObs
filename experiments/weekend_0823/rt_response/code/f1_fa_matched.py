"""F1 — FA-MATCHED H RECALL (D35 / R1-F1).

For every frozen v2 run, sweep tau so the OFF-arm frame false-alarm rate hits a
target, then read H (and E, V) frame recall at that same tau.  Two thresholding
rules are reported:
  grid  : R1's r1.py rule -- first tau on arange(0.01,1.00,0.01) with FA <= target
          (this is the rule whose numbers R1 published; reproduced to verify them)
  exact : tau from the empirical order statistics of the off-arm max-prob
          (no 0.01 quantisation -- the number we recommend for the paper)

Outputs (rt_response/):
  f1_fa_matched.json   all numbers, per run and per model
  F1_FA_MATCHED.md     the tables
  figs/f1_curve_data.json  full H-recall-vs-FA curves for the figure script
"""
import json
import os
import numpy as np
from common_rt import (BASE, MODELS, SEEDS, RUNS, load_per_frame, max_on_gt,
                       max_off_any, tau_for_fa_exact, tau_for_fa_grid, fa_at,
                       recall_at, mean_hr, halfrange)

OUT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
TARGETS = [0.359, 0.20, 0.10, 0.05]

D = {r: load_per_frame(r) for r in RUNS}

res = {"targets": TARGETS, "runs": {}, "model_mean": {}, "provenance": {
    "input": "experiments/dayrun_0820/runs/v2/{model}_s{seed}/eval_test/per_frame.csv",
    "n_off_test_frames": 408, "n_H": 96, "n_E": 45, "n_V": 180,
    "recall_rule": "frame recall = any GT-positive cell with p >= tau",
    "fa_rule": "off-arm frame FA = any of 20 cells with p >= tau",
}}

for run in RUNS:
    rows = D[run]
    off_max, _ = max_off_any(rows)
    entry = {"tau_op_0.5": {}, "grid": {}, "exact": {}}
    entry["tau_op_0.5"] = {
        "H": recall_at(rows, "H", 0.5)[0], "E": recall_at(rows, "E", 0.5)[0],
        "V": recall_at(rows, "V", 0.5)[0], "FA": fa_at(rows, 0.5)[0]}
    for tgt in TARGETS:
        tg = tau_for_fa_grid(rows, tgt)
        if tg is not None:
            entry["grid"][str(tgt)] = {
                "tau": tg, "FA": fa_at(rows, tg)[0],
                "H": recall_at(rows, "H", tg)[0], "E": recall_at(rows, "E", tg)[0],
                "V": recall_at(rows, "V", tg)[0]}
        else:
            entry["grid"][str(tgt)] = None
        te, fae = tau_for_fa_exact(off_max, tgt)
        entry["exact"][str(tgt)] = {
            "tau": te, "FA": fae,
            "H": recall_at(rows, "H", te)[0], "E": recall_at(rows, "E", te)[0],
            "V": recall_at(rows, "V", te)[0]}
    res["runs"][run] = entry

for m in MODELS:
    mm = {"tau_op_0.5": {}, "grid": {}, "exact": {}}
    for k in ("H", "E", "V", "FA"):
        vals = [res["runs"][f"{m}_s{s}"]["tau_op_0.5"][k] for s in SEEDS]
        mm["tau_op_0.5"][k] = {"mean": mean_hr(vals), "half_range": halfrange(vals),
                               "per_seed": vals}
    for rule in ("grid", "exact"):
        for tgt in TARGETS:
            cells = [res["runs"][f"{m}_s{s}"][rule][str(tgt)] for s in SEEDS]
            if any(c is None for c in cells):
                mm[rule][str(tgt)] = None
                continue
            mm[rule][str(tgt)] = {
                k: {"mean": mean_hr([c[k] for c in cells]),
                    "half_range": halfrange([c[k] for c in cells]),
                    "per_seed": [c[k] for c in cells]}
                for k in ("H", "E", "V", "FA", "tau")}
    res["model_mean"][m] = mm

# ---- full curves for the figure -------------------------------------------------
curves = {}
for run in RUNS:
    rows = D[run]
    off_max, _ = max_off_any(rows)
    h_on, _ = max_on_gt(rows, "H")
    e_on, _ = max_on_gt(rows, "E")
    v_on, _ = max_on_gt(rows, "V")
    # thresholds = every distinct score in the union, so the curve is exact
    taus = np.unique(np.concatenate([off_max, h_on, e_on, v_on, [0.0, 1.0 + 1e-9]]))
    curves[run] = {
        "tau": taus.tolist(),
        "FA": [(off_max >= t).mean() for t in taus],
        "H": [(h_on >= t).mean() for t in taus],
        "E": [(e_on >= t).mean() for t in taus],
        "V": [(v_on >= t).mean() for t in taus],
    }
json.dump(curves, open(os.path.join(OUT, "figs", "f1_curve_data.json"), "w"))

json.dump(res, open(os.path.join(OUT, "f1_fa_matched.json"), "w"), indent=1)


def f(x, nd=3):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{nd}f}"


L = []
L.append("# F1 — FA-matched H recall (RED-TEAM RESPONSE, D35 / R1-F1)\n")
L.append("Generated by `rt_response/code/f1_fa_matched.py` · CPU · read-only over the frozen v2 dumps.\n")
L.append("Input: `experiments/dayrun_0820/runs/v2/{rgb,depth,b2}_s{42,43,44}/eval_test/per_frame.csv` "
         "(816 test rows = 408 hazard-ON + 408 off).  H n=96, E n=45, V n=180, off n=408.\n")
L.append("Frame recall = *any* GT-positive cell with p ≥ τ.  Off-arm frame FA = *any* of the 20 cells "
         "with p ≥ τ.  No re-training, no re-render, no canonical file touched.\n")

L.append("\n## 1. Verification of R1's published table (grid rule, τ ∈ {0.01,…,0.99})\n")
L.append("R1 `r1.py`/`r2.py` chose, per run, the first τ on a 0.01 grid whose overall off-arm FA is ≤ target, "
         "then read H recall there, then averaged the three seeds.  Reproduced here exactly:\n")
L.append("| matched FA | RGB H | Depth H | B2 H | R1 published (RGB/Depth/B2) | match |")
L.append("|---|---|---|---|---|---|")
R1_PUB = {0.359: (0.719, 0.740, 0.385), 0.20: (0.476, 0.552, 0.198),
          0.10: (0.319, 0.510, 0.097), 0.05: (0.236, 0.479, 0.031)}
for tgt in TARGETS:
    got = [res["model_mean"][m]["grid"][str(tgt)]["H"]["mean"] for m in MODELS]
    pub = R1_PUB[tgt]
    ok = all(abs(g - p) < 5e-4 for g, p in zip(got, pub))
    L.append(f"| {tgt:.3f} | {f(got[0])} | {f(got[1])} | {f(got[2])} | "
             f"{pub[0]:.3f} / {pub[1]:.3f} / {pub[2]:.3f} | {'✓ exact' if ok else '✗ DIFFERS'} |")

L.append("\n## 2. Recommended table — exact-quantile τ (no 0.01 grid)\n")
L.append("τ is taken from the empirical order statistics of the off-arm per-frame max probability, so the "
         "achieved FA sits as close under the target as the 408 off frames allow (FA resolution = 1/408 = 0.0025).\n")
L.append("**3-seed mean H frame recall at matched off-arm FA** (± half-range over seeds):\n")
L.append("| matched FA | achieved FA (RGB/Depth/B2) | RGB H | Depth H | B2 H | Δ(Depth−RGB) |")
L.append("|---|---|---|---|---|---|")
for tgt in TARGETS:
    cells = {m: res["model_mean"][m]["exact"][str(tgt)] for m in MODELS}
    ach = " / ".join(f(cells[m]["FA"]["mean"]) for m in MODELS)
    r_, d_, b_ = (cells[m]["H"]["mean"] for m in MODELS)
    hr = {m: cells[m]["H"]["half_range"] for m in MODELS}
    L.append(f"| {tgt:.3f} | {ach} | {f(r_)} ±{f(hr['rgb'])} | **{f(d_)}** ±{f(hr['depth'])} | "
             f"{f(b_)} ±{f(hr['b2'])} | {d_ - r_:+.3f} |")

L.append("\n**Per-seed detail (exact rule).**\n")
L.append("| target FA | run | τ | achieved FA | H | E | V |")
L.append("|---|---|---|---|---|---|---|")
for tgt in TARGETS:
    for run in RUNS:
        c = res["runs"][run]["exact"][str(tgt)]
        L.append(f"| {tgt:.3f} | {run} | {c['tau']:.4f} | {f(c['FA'])} | {f(c['H'])} | "
                 f"{f(c['E'])} | {f(c['V'])} |")

L.append("\n## 3. The published operating point, for contrast (τ = 0.5, unmatched)\n")
L.append("| model | H | E | V | off-arm FA |")
L.append("|---|---|---|---|---|")
for m in MODELS:
    t = res["model_mean"][m]["tau_op_0.5"]
    L.append(f"| {m} | {f(t['H']['mean'])} ±{f(t['H']['half_range'])} | {f(t['E']['mean'])} | "
             f"{f(t['V']['mean'])} | {f(t['FA']['mean'])} |")
L.append("\nRGB reads its H recall at FA = %s; Depth reads its at FA = %s — a %.1f× difference in "
         "false-alarm rate printed in the same column." % (
             f(res["model_mean"]["rgb"]["tau_op_0.5"]["FA"]["mean"]),
             f(res["model_mean"]["depth"]["tau_op_0.5"]["FA"]["mean"]),
             res["model_mean"]["rgb"]["tau_op_0.5"]["FA"]["mean"] /
             res["model_mean"]["depth"]["tau_op_0.5"]["FA"]["mean"]))

L.append("\n## 4. V and E at matched FA (the same sweep, other tiers)\n")
L.append("| matched FA | RGB V | Depth V | B2 V | RGB E | Depth E | B2 E |")
L.append("|---|---|---|---|---|---|---|")
for tgt in TARGETS:
    c = {m: res["model_mean"][m]["exact"][str(tgt)] for m in MODELS}
    L.append("| %.3f | %s | %s | %s | %s | %s | %s |" % (
        tgt, f(c["rgb"]["V"]["mean"]), f(c["depth"]["V"]["mean"]), f(c["b2"]["V"]["mean"]),
        f(c["rgb"]["E"]["mean"]), f(c["depth"]["E"]["mean"]), f(c["b2"]["E"]["mean"])))

open(os.path.join(OUT, "F1_FA_MATCHED.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L))
